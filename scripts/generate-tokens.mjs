// Run: node scripts/generate-tokens.mjs
// Single source of truth for colour: src/theme/tokens.json.
// Writes src/styles/tokens.css. Never edit that file by hand.
import { readFileSync, writeFileSync } from "node:fs";

const tokenPairs = JSON.parse(readFileSync("src/theme/tokens.json", "utf8"));
const themes = Object.fromEntries(["dark", "light"].map((name, index) => [
  name,
  Object.fromEntries(Object.entries(tokenPairs).map(([key, values]) => [key, values[index]])),
]));
const vars = (values) =>
  Object.entries(values).map(([key, value]) => `  --th-${key}: ${value};`).join("\n");
const nonColorTokens = new Set(["page-gradient", "shadow-card", "shadow-card-hover", "shadow-modal", "public-card-shadow", "public-modal-shadow"]);
const colorMap = Object.keys(themes.dark)
  .filter((key) => !nonColorTokens.has(key))
  .map((key) => `  --color-${key === "tag-bg" ? "tag" : key}: var(--th-${key});`)
  .join("\n");
const radii = ["panel", "control", "tag", "card", "modal", "pill"];
const radiusValues = ["12px", "8px", "6px", "16px", "20px", "999px"];
const typography = `
  --text-title: 18px;
  --text-title--line-height: 24px;
  --text-title--font-weight: 500;
  --text-job: 15px;
  --text-job--line-height: 22px;
  --text-job--font-weight: 500;
  --text-control: 13px;
  --text-control--line-height: 20px;
  --text-detail: 12px;
  --text-detail--line-height: 18px;
  --text-tag: 11px;
  --text-tag--line-height: 16px;
  --text-card-title: 19px;
  --text-card-title--line-height: 25px;
  --text-card-title--font-weight: 600;
  --text-card-company: 16px;
  --text-card-company--line-height: 22px;
  --text-card-meta: 14px;
  --text-card-meta--line-height: 20px;
  --text-modal-title: 26px;
  --text-modal-title--line-height: 32px;
  --text-modal-title--font-weight: 700;
  --text-modal-body: 17px;
  --text-modal-body--line-height: 27px;`;

const rootRadii = radii.map((name, index) =>
  `  --th-radius-${name}: ${radiusValues[index]};`).join("\n");
const themeRadii = radii.map((name) =>
  `  --radius-${name}: var(--th-radius-${name});`).join("\n");
const css = `/* GENERATED by scripts/generate-tokens.mjs from src/theme/tokens.json. Do not edit by hand.
 * Dark is the default. Light applies when <html data-theme="light"> is set. */

:root {
  color-scheme: dark;
${vars(themes.dark)}
${rootRadii}
}

:root[data-theme="light"] {
  color-scheme: light;
${vars(themes.light)}
}

@theme inline {
  --font-sans: var(--font-inter), ui-sans-serif, system-ui, sans-serif;
${colorMap}
${themeRadii}
  --shadow-glow: var(--th-glow);
  --shadow-card: var(--th-shadow-card);
  --shadow-card-hover: var(--th-shadow-card-hover);
  --shadow-modal: var(--th-shadow-modal);
  --shadow-public-card: var(--th-public-card-shadow);
  --shadow-public-modal: var(--th-public-modal-shadow);
${typography}
}
`;
writeFileSync("src/styles/tokens.css", css);
console.log("Wrote src/styles/tokens.css");
