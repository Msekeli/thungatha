// Run: node scripts/generate-tokens.mjs   (or add "tokens": "node scripts/generate-tokens.mjs" to package.json)
// Single source of truth for colour: src/theme/tokens.json.
// Writes src/styles/tokens.css. Never edit that file by hand.
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync('src/theme/tokens.json', 'utf8'));
const vars = (values) => Object.entries(values).map(([k, v]) => `  --th-${k}: ${v};`).join('\n');
const colorMap = Object.keys(tokens.dark)
  .map((k) => `  --color-${k === 'tag-bg' ? 'tag' : k}: var(--th-${k});`)
  .join('\n');

const css = `/* GENERATED by scripts/generate-tokens.mjs from src/theme/tokens.json. Do not edit by hand.
 * Dark is the default. Light applies when <html data-theme="light"> is set. */

:root {
  color-scheme: dark;
${vars(tokens.dark)}

  --th-radius-panel: 12px;
  --th-radius-control: 8px;
  --th-radius-tag: 6px;
}

:root[data-theme="light"] {
  color-scheme: light;
${vars(tokens.light)}
}

/* Tailwind v4 names. "inline" makes utilities follow the theme at runtime:
   bg-panel, text-fg-muted, border-line, bg-success-bg ... */
@theme inline {
  --font-sans: var(--font-inter), ui-sans-serif, system-ui, sans-serif;

${colorMap}

  --radius-panel: var(--th-radius-panel);
  --radius-control: var(--th-radius-control);
  --radius-tag: var(--th-radius-tag);
  --shadow-glow: var(--th-glow);

  /* Typography (Inter, weights 400 and 500 only) */
  --text-title: 18px;
  --text-title--line-height: 24px;
  --text-title--font-weight: 500;
  --text-job: 15px;
  --text-job--line-height: 22px;
  --text-job--font-weight: 500;
  --text-control: 13px;
  --text-control--line-height: 20px;
  --text-detail: 12px;
  --text-detail--line-height: 18px;
  --text-tag: 11px;
  --text-tag--line-height: 16px;
}
`;
writeFileSync('src/styles/tokens.css', css);
console.log('Wrote src/styles/tokens.css');
